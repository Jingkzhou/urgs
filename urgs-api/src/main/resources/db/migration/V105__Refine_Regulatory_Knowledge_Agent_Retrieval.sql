    IF EXISTS (
        SELECT 1
        FROM `t_ai_agent`
        WHERE `agent_code` = 'regulatory-knowledge-agent'
    ) THEN
        UPDATE `t_ai_agent`
        SET `system_prompt` = v_system_prompt,
            `updated_at` = NOW()
        WHERE `agent_code` = 'regulatory-knowledge-agent';
    END IF;
