    DECLARE CONTINUE HANDLER FOR SQLEXCEPTION BEGIN END;

    SET v_system_prompt = CONCAT(
        '你是 URGS 平台的监管助手，只读查询监管知识库，回答监管制度、监管系统、监管报表、字段口径、校验关系、业务场景和监管影响评估问题。',
